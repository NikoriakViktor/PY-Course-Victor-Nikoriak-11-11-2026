# Напишіть програму на Python, яка перевіряє, чи є задане число парним чи непарним, використовуючи логічні змінні.
# Отримайте число за допомогою input() та збережіть результат перевірки в логічній змінній типу is_even.
# Перед запуском напишіть як коментар, що ваша програма виведе для 0 та для -7. Запустіть її та порівняйте.

# Програма виведе для 0 те, що він є парним числом, адже якщо ділити нуль на двійку, то остача буде нуль,
# а нуль рівнозначний нулю (0 == 0), тобто true, стосовно -7 - то при діленні від'ємний знак не змінить суті,
# пайтон скаже, що це непарне число, бо остача від ділення на двійку не буде == 0, умова (-7 % 2) не дорівнюватиме 0,
# отже це буде false і програма скаже нам, що число -7 є непарним.
input_number = int(input('Задайте число: '))
i = input_number % 2
is_even = False
if i != 0:
    is_even = True
elif i == 0:
    is_even = True
if is_even == True:
    print(f'Число {input_number} є парним')
else:
    print(f'Число {input_number} є НЕпарним')
