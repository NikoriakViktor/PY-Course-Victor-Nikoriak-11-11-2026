# в окремих змінних aта b, а потім виведіть результат для кожної з наступних дій:
# додавання, віднімання, ділення, множення, степеня, модуля, ділення на нижній точці.
# Позначте кожен рядок f-рядком і використовуйте його f"{value:.2f}"скрізь, де результат є числом з комою,
# інакше ділення виведе п'ятнадцять знаків після коми.

a = 10
b = 5.5
print(f'Додавання: {a + b}')
print(f'Віднімання: {a - b}')
print(f'Ділення: {(a / b) : .2f}')
print(f'Множення: {a * b}')
print(f'Піднесення до степеня: {(a ** b) :.2f}')
print(f'Модуль: {a % b}')
print(f'Ділення на нижній точці: {a // b}')
